const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const exportsObject = {};
vm.runInNewContext(ts.transpileModule(fs.readFileSync('src/utils/mood-rhythm.ts', 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS } }).outputText, { exports: exportsObject });
const { moodRhythm } = exportsObject;
const now = new Date(2026, 9, 7, 14);
const entry = (id, day, hour, mood = 'Good', month = 9) => { const date = new Date(2026, month, day, hour); return { id, mood, createdAt: { toDate: () => date, toMillis: () => date.getTime() } }; };
const rows = [entry('old', 5, 8, 'Low'), entry('latest', 5, 17), entry('tue', 6, 10), entry('wed', 7, 11, 'Okay'), entry('sep', 30, 10, 'Great', 8), entry('sun', 4, 10), entry('future', 8, 10), { id: 'pending', mood: 'Low', createdAt: null }];
let data = moodRhythm(rows, 'This Week', now);
assert.equal(data.count, 3); assert.equal(data.weekEntries, 4); assert.equal(data.week[0].entry.id, 'latest');
assert.equal(data.week[2].today, true); assert.equal(data.week[3].entry, undefined);
assert.equal(data.frequent[0], 'Good'); assert.equal(data.frequent[1], 2); assert.equal(data.streak, 4);
assert.equal(data.status, 'Building rhythm'); assert.equal(data.recent.length, 4);
assert.equal(moodRhythm(rows, 'Month', now).recent.length, 5);
assert.equal(moodRhythm(rows, 'All Time', now).recent.length, rows.length);
data = moodRhythm([], 'This Week', now); assert.equal(data.count, 0); assert.equal(data.streak, 0); assert.equal(data.frequent, undefined);
assert.equal(moodRhythm([entry('yesterday', 6, 10)], 'This Week', now).streak, 1);
assert.equal(moodRhythm([entry('stale', 5, 10)], 'This Week', now).streak, 0);
const sunday = moodRhythm(rows, 'This Week', new Date(2026, 9, 11, 15));
assert.equal(sunday.week[0].date.getDate(), 5); assert.equal(sunday.week[6].today, true);
const monday = moodRhythm([entry('sun', 4, 10)], 'This Week', new Date(2026, 9, 5, 15));
assert.equal(monday.count, 0); assert.equal(monday.streak, 1);
console.log('PASS: real entry aggregation, latest daily mood, week/month ranges, distinct-day frequency, active streak, missing timestamps, empty data and week boundaries.');
